"""Flagged expenses and the questions about them.

An expense is flagged to look at again. Each flag has a comment thread: anyone signed in can add a
comment, and a comment can be put to a named person ("ask"), who then has it waiting on them until
they reply. A flag is open until someone resolves it; resolving keeps the thread.

`transactions.flagged` stays 1 while a flag is open, so the existing flag icons and counts keep working.
"""
from datetime import datetime, timezone

SCHEMA = """
CREATE TABLE IF NOT EXISTS flag_comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id INTEGER NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
    author_email TEXT, author_name TEXT NOT NULL, body TEXT NOT NULL,
    ask_email TEXT, ask_name TEXT, created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS flag_comments_txn ON flag_comments(txn_id);
"""
_COLUMNS = [("flag_state", "TEXT"), ("flagged_by", "TEXT"), ("flagged_at", "TEXT"),
            ("flag_resolved_by", "TEXT"), ("flag_resolved_at", "TEXT")]
OPEN, RESOLVED = "open", "resolved"
MAX_COMMENT = 4000


def ensure(conn) -> None:
    for stmt in SCHEMA.split(";"):
        if stmt.strip():
            conn.execute(stmt)
    for name, kind in _COLUMNS:
        conn.execute(f"ALTER TABLE transactions ADD COLUMN IF NOT EXISTS {name} {kind}")
    # Expenses flagged before flags had pages are open flags.
    conn.execute("UPDATE transactions SET flag_state = ? WHERE flagged = 1 AND flag_state IS NULL", (OPEN,))


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _txn(conn, txn_id: int):
    t = conn.execute("SELECT * FROM transactions WHERE id = ?", (txn_id,)).fetchone()
    if not t:
        raise ValueError("Expense not found.")
    return t


def people(conn, owner_email: str = "", owner_name: str = "") -> list[dict]:
    """Who a question can be put to: the owner and every active user."""
    out = []
    if owner_email:
        out.append({"email": owner_email.lower(), "name": owner_name or "Owner"})
    for r in conn.execute("SELECT email, first_name, last_name FROM users WHERE active = 1 "
                          "ORDER BY first_name, last_name"):
        if r["email"].lower() != owner_email.lower():
            out.append({"email": r["email"].lower(), "name": f"{r['first_name']} {r['last_name']}".strip()})
    return out


def set_flag(conn, txn_id: int, flagged: bool, person: dict | None = None) -> None:
    """Flag an expense (opens it), or take the flag off. A flag that has comments is resolved
    rather than wiped, so the questions and answers stay on record."""
    t = _txn(conn, txn_id)
    who = (person or {}).get("name") or ""
    with conn:
        if flagged:
            conn.execute("UPDATE transactions SET flagged = 1, flag_state = ?, flagged_by = ?, flagged_at = ?, "
                         "flag_resolved_by = NULL, flag_resolved_at = NULL WHERE id = ?",
                         (OPEN, who or t["flagged_by"], _now(), txn_id))
        else:
            has_comments = conn.execute("SELECT 1 FROM flag_comments WHERE txn_id = ? LIMIT 1", (txn_id,)).fetchone()
            if has_comments:
                conn.execute("UPDATE transactions SET flagged = 0, flag_state = ?, flag_resolved_by = ?, "
                             "flag_resolved_at = ? WHERE id = ?", (RESOLVED, who, _now(), txn_id))
            else:
                conn.execute("UPDATE transactions SET flagged = 0, flag_state = NULL, flagged_by = NULL, "
                             "flagged_at = NULL, flag_resolved_by = NULL, flag_resolved_at = NULL WHERE id = ?",
                             (txn_id,))


def set_state(conn, txn_id: int, state: str, person: dict) -> None:
    """Resolve an open flag, or reopen a resolved one."""
    if state not in (OPEN, RESOLVED):
        raise ValueError("Unknown flag state.")
    t = _txn(conn, txn_id)
    if not t["flag_state"]:
        raise ValueError("That expense isn't flagged.")
    with conn:
        if state == RESOLVED:
            conn.execute("UPDATE transactions SET flagged = 0, flag_state = ?, flag_resolved_by = ?, "
                         "flag_resolved_at = ? WHERE id = ?", (RESOLVED, person.get("name") or "", _now(), txn_id))
        else:
            conn.execute("UPDATE transactions SET flagged = 1, flag_state = ?, flag_resolved_by = NULL, "
                         "flag_resolved_at = NULL WHERE id = ?", (OPEN, txn_id))


def add_comment(conn, txn_id: int, person: dict, body: str, ask_email: str = "",
                everyone: list[dict] | None = None) -> dict:
    """Add a comment, optionally putting it to someone. Commenting on an expense that isn't flagged
    flags it; asking someone on a resolved flag reopens it."""
    t = _txn(conn, txn_id)
    text = str(body or "").strip()
    if not text:
        raise ValueError("Write a comment first.")
    if len(text) > MAX_COMMENT:
        raise ValueError(f"Keep a comment under {MAX_COMMENT} characters.")
    ask_email = str(ask_email or "").strip().lower()
    ask_name = None
    if ask_email:
        match = next((p for p in (everyone or []) if p["email"] == ask_email), None)
        if not match:
            raise ValueError("Pick someone from the list to ask.")
        ask_name = match["name"]
    with conn:
        conn.execute("INSERT INTO flag_comments (txn_id, author_email, author_name, body, ask_email, ask_name, "
                     "created_at) VALUES (?, ?, ?, ?, ?, ?, ?)",
                     (txn_id, (person.get("email") or "").lower(), person.get("name") or "Someone", text,
                      ask_email or None, ask_name, _now()))
        if not t["flag_state"] or (t["flag_state"] == RESOLVED and ask_email):
            conn.execute("UPDATE transactions SET flagged = 1, flag_state = ?, flagged_by = COALESCE(flagged_by, ?), "
                         "flagged_at = COALESCE(flagged_at, ?), flag_resolved_by = NULL, flag_resolved_at = NULL "
                         "WHERE id = ?", (OPEN, person.get("name") or "", _now(), txn_id))
    return get_flag(conn, txn_id)


def _waiting_on(comments: list[dict]) -> dict | None:
    """The person the latest unanswered question was put to: asked, and they haven't commented since."""
    waiting = None
    for c in comments:
        if waiting and c["author_email"] == waiting["email"]:
            waiting = None
        if c["ask_email"]:
            waiting = {"email": c["ask_email"], "name": c["ask_name"]}
    return waiting


def _comments(conn, txn_ids: list[int]) -> dict[int, list[dict]]:
    out: dict[int, list[dict]] = {i: [] for i in txn_ids}
    if not txn_ids:
        return out
    marks = ", ".join("?" for _ in txn_ids)
    for r in conn.execute(f"SELECT * FROM flag_comments WHERE txn_id IN ({marks}) ORDER BY created_at, id",
                          tuple(txn_ids)):
        out[r["txn_id"]].append(dict(r))
    return out


def _flag_row(t, comments: list[dict]) -> dict:
    last = comments[-1] if comments else None
    return {
        "id": t["id"], "date": t["date"], "description": t["description"], "amount": t["amount"],
        "category": t["category"], "expense_type": t.get("expense_type"), "car_id": t["car_id"],
        "state": t["flag_state"], "flagged_by": t["flagged_by"], "flagged_at": t["flagged_at"],
        "resolved_by": t["flag_resolved_by"], "resolved_at": t["flag_resolved_at"],
        "comments": len(comments), "last_comment": last, "waiting_on": _waiting_on(comments),
    }


def list_flags(conn, status: str = OPEN, me_email: str = "") -> list[dict]:
    """Flags for the Flags page: open, resolved, all, or waiting on `me_email`, newest activity first."""
    where = {"all": "flag_state IS NOT NULL", RESOLVED: "flag_state = 'resolved'"}.get(status, "flag_state = 'open'")
    rows = conn.execute(f"SELECT * FROM transactions WHERE {where}").fetchall()
    regs = {r["id"]: r["reg"] for r in conn.execute("SELECT id, reg FROM cars")}
    threads = _comments(conn, [r["id"] for r in rows])
    out = []
    for t in rows:
        f = _flag_row(t, threads[t["id"]])
        f["car_reg"] = regs.get(t["car_id"])
        out.append(f)
    if status == "waiting":
        me = (me_email or "").lower()
        out = [f for f in out if f["waiting_on"] and f["waiting_on"]["email"] == me]
    out.sort(key=lambda f: (f["last_comment"] or {}).get("created_at") or f["flagged_at"] or "", reverse=True)
    return out


def counts(conn, me_email: str = "") -> dict:
    """For the sidebar: open flags, and those waiting on this person."""
    rows = conn.execute("SELECT id FROM transactions WHERE flag_state = 'open'").fetchall()
    threads = _comments(conn, [r["id"] for r in rows])
    me = (me_email or "").lower()
    waiting = sum(1 for c in threads.values() if (w := _waiting_on(c)) and w["email"] == me)
    return {"open": len(rows), "waiting": waiting}


def get_flag(conn, txn_id: int) -> dict:
    t = _txn(conn, txn_id)
    thread = _comments(conn, [txn_id])[txn_id]
    reg = conn.execute("SELECT reg FROM cars WHERE id = ?", (t["car_id"],)).fetchone() if t["car_id"] else None
    return {**_flag_row(t, thread), "car_reg": reg["reg"] if reg else None, "thread": thread,
            "vat": t["vat"], "notes": t["notes"], "paid_by": t.get("paid_by") or "Bank",
            "receipts": conn.execute("SELECT COUNT(*) AS n FROM receipts WHERE txn_id = ?", (txn_id,)).fetchone()["n"]}
