def connect(url: str | None = None, schema: str | None = None, files_dir: str | Path | None = None):
    """Open the admin database: DATABASE_URL, tables in the ADMIN_DB_SCHEMA schema."""
    url = url or os.environ.get("DATABASE_URL")
    if not url:
        raise RuntimeError("DATABASE_URL isn't set: point it at the PostgreSQL database.")
    conn = pg.connect(url, schema or os.environ.get("ADMIN_DB_SCHEMA") or "admin")
    conn.files_dir = Path(files_dir or DATA_DIR)
    conn.files_dir.mkdir(parents=True, exist_ok=True)
    conn.executescript(SCHEMA)
    for table, column, kind in _MIGRATIONS:
        conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {kind}")
    conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS cars_stock_no ON cars(stock_no)")
    with conn:
        for old, new in _RETIRED_STATUSES.items():
            conn.execute("UPDATE cars SET status = ? WHERE status = ?", (new, old))
        for (car_id,) in conn.execute("SELECT id FROM cars WHERE stock_no IS NULL ORDER BY id").fetchall():
            conn.execute("UPDATE cars SET stock_no = ? WHERE id = ?", (next_stock_no(conn), car_id))
    restore_files(conn)
    return conn


def receipts_dir(conn) -> Path:
    """The local working copy of receipts (the originals are in the files table)."""
    return conn.files_dir / "receipts"


# ---------------------------------------------------------------- stored files

def _file_key(conn, path: Path) -> str:
    return Path(path).resolve().relative_to(conn.files_dir.resolve()).as_posix()


def store_file(conn, path: Path) -> None:
    """Save a file written under the working folder into the database, so it outlives restarts."""
    with conn:
        conn.execute("INSERT INTO files (path, data, updated_at) VALUES (?, ?, ?) "
                     "ON CONFLICT (path) DO UPDATE SET data = EXCLUDED.data, updated_at = EXCLUDED.updated_at",
                     (_file_key(conn, path), Path(path).read_bytes(), datetime.now().isoformat(timespec="seconds")))


def drop_file(conn, path: Path) -> None:
    Path(path).unlink(missing_ok=True)
    with conn:
        conn.execute("DELETE FROM files WHERE path = ?", (_file_key(conn, path),))


def restore_files(conn) -> int:
    """Rebuild the local working folder from the database (on start, e.g. after a deploy)."""
    n = 0
    for r in conn.execute("SELECT path, data FROM files"):
        target = conn.files_dir / r["path"]
        if not target.exists():
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(bytes(r["data"]))
            n += 1
    return n


