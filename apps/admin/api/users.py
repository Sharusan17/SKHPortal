"""People who can sign in besides the owner, what each role may see and do, and the queue of
changes a user makes that wait for an admin to approve.

Roles
  admin  everything, and their changes apply straight away. The owner (ADMIN_EMAIL) is always
         an admin and can't be removed, so the business can never be locked out.
  user   Home, Stock Book, Invoices and Expenses only. Never the bank, the VAT return, the
         business settings or other users. Whatever they save waits for an admin (see `queue`).

Admins switch areas on or off for users on the Users page (`PERMISSIONS`, all on by default).
"""
from __future__ import annotations

import base64
import json
import re
from datetime import datetime, timezone

import auth as admin_auth

ROLES = {"admin": "Admin", "user": "User"}
MIN_PASSWORD = 8

# What users may change, each an on/off toggle for admins. Key -> label.
PERMISSIONS = {
    "invoices": "Create and edit invoices (payments, credit notes)",
    "stock": "Add and edit vehicles in the stock book",
    "expenses": "Add and edit expenses",
    "documents": "Attach and remove documents and receipts",
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL, last_name TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user', active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS app_settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS change_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email TEXT NOT NULL, user_name TEXT NOT NULL,
    created_at TEXT NOT NULL, method TEXT NOT NULL, path TEXT NOT NULL, query TEXT NOT NULL DEFAULT '',
    content_type TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '', summary TEXT NOT NULL,
    details TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'pending',
    decided_by TEXT, decided_at TEXT, note TEXT
);
"""


def ensure(conn) -> None:
    for stmt in SCHEMA.split(";"):
        if stmt.strip():
            conn.execute(stmt)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _clean_email(email) -> str:
    return str(email or "").strip().lower()


# ---------------------------------------------------------------- accounts

def _public(r) -> dict:
    r = dict(r)
    r.pop("password_hash", None)
    r["active"] = bool(r["active"])
    r["name"] = f"{r['first_name']} {r['last_name']}".strip()
    return r


def list_users(conn) -> list[dict]:
    return [_public(r) for r in conn.execute("SELECT * FROM users ORDER BY active DESC, first_name, last_name")]


def get_by_email(conn, email) -> dict | None:
    r = conn.execute("SELECT * FROM users WHERE email = ?", (_clean_email(email),)).fetchone()
    return dict(r) if r else None


def _check_password(pw: str) -> None:
    if len(pw or "") < MIN_PASSWORD:
        raise ValueError(f"Passwords need at least {MIN_PASSWORD} characters.")


def create_user(conn, data: dict, owner_email: str) -> dict:
    first, last, email = str(data.get("first_name") or "").strip(), str(data.get("last_name") or "").strip(), \
        _clean_email(data.get("email"))
    role = data.get("role") or "user"
    if not first:
        raise ValueError("Enter their first name.")
    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
        raise ValueError("Enter a valid email address.")
    if email == _clean_email(owner_email):
        raise ValueError("That's the owner's email, which already signs in as an admin.")
    if role not in ROLES:
        raise ValueError("Pick Admin or User.")
    _check_password(data.get("password"))
    if get_by_email(conn, email):
        raise ValueError("Someone already uses that email.")
    with conn:
        conn.execute("INSERT INTO users (first_name, last_name, email, password_hash, role, active, created_at) "
                     "VALUES (?, ?, ?, ?, ?, 1, ?)",
                     (first, last, email, admin_auth.hash_password(data["password"]), role, _now()))
    return _public(get_by_email(conn, email))


def update_user(conn, user_id: int, data: dict, acting_email: str) -> dict:
    r = conn.execute("SELECT * FROM users WHERE id = ?", (user_id,)).fetchone()
    if not r:
        raise ValueError("User not found.")
    fields = {}
    if "first_name" in data:
        if not str(data["first_name"] or "").strip():
            raise ValueError("Enter their first name.")
        fields["first_name"] = str(data["first_name"]).strip()
    if "last_name" in data:
        fields["last_name"] = str(data["last_name"] or "").strip()
    if "role" in data:
        if data["role"] not in ROLES:
            raise ValueError("Pick Admin or User.")
        fields["role"] = data["role"]
    if "active" in data:
        fields["active"] = 1 if data["active"] else 0
    if data.get("password"):  # an admin setting a new password for someone who forgot theirs
        _check_password(data["password"])
        fields["password_hash"] = admin_auth.hash_password(data["password"])
    if r["email"] == _clean_email(acting_email) and (fields.get("role", "admin") != "admin" or fields.get("active") == 0):
        raise ValueError("You can't take away your own admin access or switch yourself off.")
    if fields:
        with conn:
            conn.execute(f"UPDATE users SET {', '.join(f'{k} = ?' for k in fields)} WHERE id = ?",
                         (*fields.values(), user_id))
    return _public(conn.execute("SELECT * FROM users WHERE id = ?", (user_id,)).fetchone())


def change_own_password(conn, email: str, current: str, new: str) -> None:
    r = get_by_email(conn, email)
    if not r:
        raise ValueError("The owner's password is set on Railway (ADMIN_PASSWORD_HASH), not here.")
    if not admin_auth.check_password(current or "", r["password_hash"]):
        raise ValueError("Your current password isn't right.")
    _check_password(new)
    with conn:
        conn.execute("UPDATE users SET password_hash = ? WHERE id = ?", (admin_auth.hash_password(new), r["id"]))


# ---------------------------------------------------------------- toggles

def permissions(conn) -> dict[str, bool]:
    r = conn.execute("SELECT value FROM app_settings WHERE key = 'user_permissions'").fetchone()
    saved = json.loads(r["value"]) if r else {}
    return {k: bool(saved.get(k, True)) for k in PERMISSIONS}


def set_permissions(conn, data: dict) -> dict[str, bool]:
    now = {**permissions(conn), **{k: bool(v) for k, v in data.items() if k in PERMISSIONS}}
    with conn:
        conn.execute("INSERT INTO app_settings (key, value) VALUES ('user_permissions', ?) "
                     "ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value", (json.dumps(now),))
    return now


# ---------------------------------------------------------------- who is this, and may they?

def owner_name(conn) -> dict:
    """The owner's name: the Owner name in Business details (also editable on the Users page).
    The owner's email and password come from Railway, not from here."""
    try:
        r = conn.execute("SELECT owner_name FROM business WHERE id = 1").fetchone()
    except Exception:  # no business row yet
        r = None
    full = " ".join(str((r["owner_name"] if r else "") or "").split())
    if not full:
        return {"first_name": "Owner", "last_name": "", "name": "Owner"}
    first, _, last = full.partition(" ")
    return {"first_name": first, "last_name": last, "name": full}


def set_owner_name(conn, first: str, last: str) -> dict:
    full = " ".join(f"{first or ''} {last or ''}".split())
    if not full:
        raise ValueError("Enter the owner's first name.")
    if len(full) > 120:
        raise ValueError("Keep the name under 120 characters.")
    with conn:
        cur = conn.execute("UPDATE business SET owner_name = ? WHERE id = 1", (full,))
    if not cur.rowcount:
        raise ValueError("Fill in the Business details first.")
    return owner_name(conn)


def who(conn, auth: admin_auth.Auth, email: str | None) -> dict | None:
    """The signed-in person for a session email: the owner, or an active user. None otherwise."""
    if not email:
        return None
    if auth.is_owner(email):
        return {"email": auth.email, **owner_name(conn), "role": "admin", "owner": True}
    r = get_by_email(conn, email)
    if not r or not r["active"]:
        return None
    return {**_public(r), "owner": False}


# Pages a user sees (the rest are hidden and refused).
USER_PAGES = ["home", "stock", "invoices", "expenses", "flags", "reports"]

# Reads a user may make. Everything else under /api/ is refused for users.
_USER_READS = [
    r"/api/auth/.*", r"/api/version", r"/api/meta", r"/api/business", r"/api/logo", r"/api/periods",
    r"/api/quarters", r"/api/home", r"/api/reminders", r"/api/stock", r"/api/cars(/.*)?",
    r"/api/vehicle-lookup", r"/api/documents/\d+/file", r"/api/expenses(/\d+)?",
    r"/api/transactions/\d+/receipts", r"/api/receipts/\d+/file", r"/api/invoices(/.*)?",
    r"/api/credit-notes(/.*)?", r"/api/approvals(/.*)?", r"/api/me(/.*)?",
    r"/api/flags(/\d+)?", r"/api/people", r"/api/report",
]
_USER_READS_BLOCKED = [r"/api/cars/\d+/purchase-payment"]

# POSTs that only work something out and change nothing: run them straight away.
_USER_LOOKUPS = [r"/api/sale-preview", r"/api/invoices/totals", r"/api/invoices/check",
                 r"/api/invoices/draft\.png", r"/api/invoices/draft\.pdf", r"/api/auth/.*",
                 r"/api/me/password"]

# Changes a user may ask for, by area: (method, path pattern, area).
_USER_WRITES = [
    ("POST", r"/api/cars", "stock"), ("PATCH", r"/api/cars/\d+", "stock"),
    ("POST", r"/api/cars/\d+/sale", "stock"), ("POST", r"/api/cars/\d+/check", "stock"),
    ("POST", r"/api/cars/\d+/documents", "documents"), ("PATCH", r"/api/documents/\d+", "documents"),
    ("DELETE", r"/api/documents/\d+", "documents"),
    ("POST", r"/api/expenses", "expenses"), ("PATCH", r"/api/expenses/\d+", "expenses"),
    ("DELETE", r"/api/expenses/\d+", "expenses"),
    ("POST", r"/api/transactions/\d+/receipts", "documents"), ("DELETE", r"/api/receipts/\d+", "documents"),
    ("POST", r"/api/invoices", "invoices"), ("PUT", r"/api/invoices/\d+", "invoices"),
    ("POST", r"/api/invoices/\d+/(regenerate|void|payments|credit-notes|refunds)", "invoices"),
    ("DELETE", r"/api/payments/\d+", "invoices"),
]

# Admin-only, whatever the method.
_ADMIN_ONLY = [r"/api/users(/.*)?", r"/api/settings/.*", r"/api/approvals/\d+/(approve|reject)"]


def _match(patterns, path) -> bool:
    return any(re.fullmatch(p, path) for p in patterns)


def decide(person: dict, method: str, path: str, perms: dict[str, bool]) -> tuple[str, str]:
    """What happens to a request: ("allow", ""), ("queue", area) or ("deny", reason)."""
    if person["role"] == "admin":
        return "allow", ""
    if _match(_ADMIN_ONLY, path):
        return "deny", "Only an admin can do that."
    if method in ("GET", "HEAD"):
        if _match(_USER_READS, path) and not _match(_USER_READS_BLOCKED, path):
            return "allow", ""
        return "deny", "That part of the app is for admins."
    if method == "POST" and _match(_USER_LOOKUPS, path):
        return "allow", ""
    # Questions and answers on flags are a conversation, not a change to the books: no approval.
    if method == "POST" and re.fullmatch(r"/api/flags/\d+/(comments|state)", path):
        return "allow", ""
    for m, pattern, area in _USER_WRITES:
        if m == method and re.fullmatch(pattern, path):
            if not perms.get(area, True):
                return "deny", "Your admin has switched that off for users."
            return "queue", area
    return "deny", "Only an admin can do that."


# ---------------------------------------------------------------- the approval queue

_WHAT = [  # (method, pattern, words) for a readable summary
    ("POST", r"/api/cars", "Add a car to the stock book"), ("PATCH", r"/api/cars/(\d+)", "Change car"),
    ("POST", r"/api/cars/(\d+)/sale", "Record a sale for car"), ("POST", r"/api/cars/(\d+)/check", "Check car details for"),
    ("POST", r"/api/cars/(\d+)/documents", "Add documents to car"), ("PATCH", r"/api/documents/(\d+)", "Rename document"),
    ("DELETE", r"/api/documents/(\d+)", "Delete document"),
    ("POST", r"/api/expenses", "Add an expense"), ("PATCH", r"/api/expenses/(\d+)", "Change expense"),
    ("DELETE", r"/api/expenses/(\d+)", "Delete expense"),
    ("POST", r"/api/transactions/(\d+)/receipts", "Attach receipts to expense"),
    ("DELETE", r"/api/receipts/(\d+)", "Delete receipt"),
    ("POST", r"/api/invoices", "Create an invoice"), ("PUT", r"/api/invoices/(\d+)", "Change invoice"),
    ("POST", r"/api/invoices/(\d+)/regenerate", "Re-generate the PDF of invoice"),
    ("POST", r"/api/invoices/(\d+)/void", "Void invoice"),
    ("POST", r"/api/invoices/(\d+)/payments", "Record a payment on invoice"),
    ("POST", r"/api/invoices/(\d+)/credit-notes", "Raise a credit note on invoice"),
    ("POST", r"/api/invoices/(\d+)/refunds", "Record a refund on invoice"),
    ("DELETE", r"/api/payments/(\d+)", "Remove payment"),
]


def _label_for(conn, path: str, words: str, ref: str | None) -> str:
    """Words plus what the id points at (a reg, an invoice number, a description) where we can."""
    if not ref:
        return words
    try:
        if "/cars/" in path:
            r = conn.execute("SELECT reg FROM cars WHERE id = ?", (int(ref),)).fetchone()
            return f"{words} {r['reg'] or ref}" if r else f"{words} {ref}"
        if "/invoices/" in path:
            r = conn.execute("SELECT invoice_no FROM invoices WHERE id = ?", (int(ref),)).fetchone()
            return f"{words} {r['invoice_no']}" if r else f"{words} {ref}"
        if "/expenses/" in path or "/transactions/" in path:
            r = conn.execute("SELECT description FROM transactions WHERE id = ?", (int(ref),)).fetchone()
            return f"{words}: {r['description']}" if r else f"{words} {ref}"
    except Exception:  # a summary is only a label; never fail a request over it
        pass
    return f"{words} {ref}"


def summarise(conn, method: str, path: str, content_type: str, body: bytes) -> tuple[str, str]:
    """A one-line summary and the details (the fields sent, file names for uploads)."""
    words, ref = f"{method} {path}", None
    for m, pattern, w in _WHAT:
        hit = re.fullmatch(pattern, path)
        if m == method and hit:
            words, ref = w, (hit.group(1) if hit.groups() else None)
            break
    summary = _label_for(conn, path, words, ref)
    details = ""
    if "application/json" in content_type and body:
        try:
            data = json.loads(body)
            details = json.dumps(data, indent=2, ensure_ascii=False, default=str)[:20000]
            if isinstance(data, dict):  # name the thing being added, where there is one
                extra = data.get("reg") or data.get("description") or data.get("buyer_name")
                if extra and not ref:
                    summary = f"{summary}: {extra}"
        except ValueError:
            details = ""
    elif "multipart/form-data" in content_type and body:
        names = re.findall(rb'filename="([^"]*)"', body)
        if names:
            details = "Files: " + ", ".join(n.decode("utf-8", "replace") for n in names)
            summary = f"{summary} ({len(names)} file{'s' if len(names) != 1 else ''})"
    return summary, details


def queue(conn, person: dict, method: str, path: str, query: str, content_type: str, body: bytes) -> dict:
    summary, details = summarise(conn, method, path, content_type, body)
    with conn:
        r = conn.execute(
            "INSERT INTO change_requests (user_email, user_name, created_at, method, path, query, content_type, "
            "body, summary, details) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?) RETURNING *",
            (person["email"], person["name"], _now(), method, path, query, content_type,
             base64.b64encode(body or b"").decode(), summary, details)).fetchone()
    return _request_public(r)


def _request_public(r) -> dict:
    r = dict(r)
    r.pop("body", None)
    return r


def list_requests(conn, person: dict, status: str | None = None) -> list[dict]:
    sql, params = "SELECT * FROM change_requests", []
    where = []
    if person["role"] != "admin":
        where.append("user_email = ?")
        params.append(person["email"])
    if status:
        where.append("status = ?")
        params.append(status)
    if where:
        sql += " WHERE " + " AND ".join(where)
    return [_request_public(r) for r in conn.execute(sql + " ORDER BY id DESC LIMIT 300", params)]


def pending_count(conn, person: dict) -> int:
    if person["role"] == "admin":
        r = conn.execute("SELECT COUNT(*) AS n FROM change_requests WHERE status = 'pending'").fetchone()
    else:
        r = conn.execute("SELECT COUNT(*) AS n FROM change_requests WHERE status = 'pending' AND user_email = ?",
                         (person["email"],)).fetchone()
    return r["n"]


def get_request(conn, request_id: int) -> dict | None:
    r = conn.execute("SELECT * FROM change_requests WHERE id = ?", (request_id,)).fetchone()
    return dict(r) if r else None


def body_of(req: dict) -> bytes:
    return base64.b64decode(req.get("body") or "")


def close_request(conn, request_id: int, status: str, admin: dict, note: str = "") -> None:
    with conn:
        conn.execute("UPDATE change_requests SET status = ?, decided_by = ?, decided_at = ?, note = ?, body = '' "
                     "WHERE id = ?", (status, admin.get("name") or "Owner", _now(),
                                      note[:2000], request_id))
